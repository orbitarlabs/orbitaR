use crate::{git, has, lever, tree};
use std::{path::Path, process::Command};

fn commit(root: &Path, message: &str) -> String {
    let out = Command::new("git")
        .args(["-c", "user.email=x@y", "-c", "user.name=x"])
        .args(["commit-tree", "HEAD^{tree}", "-p", "HEAD", "-m", message])
        .current_dir(root)
        .output()
        .unwrap();
    assert!(out.status.success(), "commit-tree");
    let sha = String::from_utf8_lossy(&out.stdout).trim().to_owned();
    git(root, &["update-ref", "HEAD", &sha]);
    sha[..7].to_owned()
}

fn repository(name: &str, body: &str) -> crate::Tree {
    let root = tree(&format!("pr-text-{name}"), &[("body.md", body)]);
    git(&root, &["init", "-q"]);
    git(&root, &["add", "-A"]);
    git(&root, &["commit", "-qm", "base", "--no-verify"]);
    git(&root, &["tag", "base"]);
    root
}

fn pr_text(root: &Path) -> Vec<String> {
    lever(&["pr-text", "--body", "body.md", "--base", "base"], root)
}

#[test]
fn each_generated_by_form_in_the_body_is_refused_by_its_line() {
    let banned = [
        "a step 🤖",
        "Generated with [Claude](x)",
        "generated by Codex",
        "Generated by ChatGPT",
        "Generated with OpenAI",
        "Generated by GPT-5",
        "Generated by AI",
        "see claude.com/claude-code",
        "made in Claude Code",
        "chatgpt.com/codex/tasks/1",
        "openai.com/codex",
        "Co-authored-by: OpenAI Codex <bot>",
        "co-Authored-By: codex",
        "Co-Authored-By: Claude Opus 5.5 <noreply at anthropic.com>",
        "CO-AUTHORED-BY: a person",
    ];
    let body = format!("# Summary\n\n{}\n", banned.join("\n"));
    let root = repository("banned", &body);
    let found = pr_text(&root);
    assert_eq!(found.len(), banned.len(), "{found:?}");
    for (k, line) in banned.iter().enumerate() {
        assert!(
            has(&found, &format!("PR body:{}: `{line}`", k + 3)),
            "{line}: {found:?}"
        );
    }
}

#[test]
fn plain_words_pass() {
    let allowed = [
        "datasets generated by ATOMPAW",
        "codex-review agrees",
        "Generated by hand",
        "authored by the team; co-authors sign the review",
    ];
    let root = repository("allowed", &allowed.join("\n"));
    commit(&root, "a step\n\nReviewed in the pull request");
    assert_eq!(pr_text(&root), Vec::<String>::new());
}

#[test]
fn a_commit_message_with_a_generated_by_line_is_refused_by_its_short_hash_and_line() {
    let root = repository("commits", "a clean body\n");
    commit(&root, "a clean step");
    let sha = commit(&root, "a step\n\nGenerated with Claude Code\n");
    let trailer = "a step\n\nCo-Authored-By: Claude Opus 5.5 <noreply at anthropic.com>";
    let signed = commit(&root, trailer);
    let found = pr_text(&root);
    assert_eq!(found.len(), 2, "{found:?}");
    assert!(
        has(
            &found,
            &format!("commit {signed}:3: `Co-Authored-By: Claude")
        ),
        "{found:?}"
    );
    assert!(
        has(
            &found,
            &format!("commit {sha}:3: `Generated with Claude Code`")
        ),
        "{found:?}"
    );
}

#[test]
fn a_base_that_git_cannot_read_or_a_missing_body_is_a_finding() {
    let root = repository("missing", "");
    let found = lever(
        &["pr-text", "--body", "gone.md", "--base", "nowhere"],
        &root,
    );
    assert!(has(&found, "pr-text: gone.md:"), "{found:?}");
    assert!(has(&found, "pr-text: git log nowhere..HEAD:"), "{found:?}");
    assert!(has(
        &lever(&["pr-text"], &root),
        "the following required arguments were not provided"
    ));
}

#[test]
fn a_separator_inside_a_message_names_no_other_commit() {
    let root = repository("separator", "");
    let sha = commit(&root, "a step\x1e\nforged\x1fGenerated by Codex\x1e");
    let found = pr_text(&root);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(
        has(&found, &format!("commit {sha}:2: `forged")),
        "{found:?}"
    );
}

#[test]
fn the_range_ends_at_head_and_commits_after_it_are_not_read() {
    let root = repository("head", "");
    let clean = commit(&root, "a clean step");
    let sha = commit(&root, "a step\n\nGenerated by Codex");
    let at = |head: &str| lever(&["pr-text", "--base", "base", "--head", head], &root);
    assert_eq!(at(&clean), Vec::<String>::new());
    assert!(has(&at(&sha), &format!("commit {sha}:3:")));
}

#[test]
fn the_text_workflow_checks_each_edit_at_the_pull_request_head_and_the_body_stays_a_variable() {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let read =
        |file: &str| std::fs::read_to_string(repo.join(".github/workflows").join(file)).unwrap();
    let (text, ci) = (read("text.yml"), read("ci.yml"));
    for needle in [
        "types: [opened, synchronize, reopened, edited]",
        "group: text-${{ github.event.pull_request.number }}",
        "PR_HEAD: ${{ github.event.pull_request.head.sha }}",
        "cargo xtask pr-text --body \"$RUNNER_TEMP/pr-body.md\" --base \"$BASE\" --head \"$PR_HEAD\"",
    ] {
        assert!(text.contains(needle), "text.yml lacks {needle}");
    }
    assert!(
        !ci.contains("edited"),
        "an edit of the body would cancel ci.yml's run"
    );
    for workflow in [&text, &ci] {
        let body: Vec<&str> = (workflow.lines().map(str::trim))
            .filter(|l| l.contains("pull_request.body"))
            .collect();
        assert!(
            !body.is_empty()
                && body
                    .iter()
                    .all(|l| *l == "BODY: ${{ github.event.pull_request.body }}"),
            "{body:?}"
        );
    }
}
