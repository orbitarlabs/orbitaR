use crate::{
    Findings,
    case::{self, Reference},
    results,
    syntax::{self, Tree},
    walk,
};
use proc_macro2::Delimiter;
use std::{collections::BTreeSet, fs, path::Path};

pub(crate) const MAP: &str = concat!(
    "  src/<dir>/<file>.rs         ↔  tests/<dir>/<file>.rs          public API only, one test binary\n",
    "  xtask/src/<file>.rs         ↔  xtask/tests/<file>.rs          seeded failures for each lever\n",
    "  benchmarks/<N>_<slug>/      ↔  tests/benchmarks/<N>_<slug>/   data + measure(); the harness judges\n",
    "  tests/benchmarks.rs            the case table, generated by new-case",
);

const TREES: [(&str, &str); 2] = [("src", "tests"), ("xtask/src", "xtask/tests")];
pub(crate) const RUNNER: &str = "tests/benchmarks.rs";
pub(crate) const BEGIN: &str =
    "// cases: begin (generated by `cargo xtask new-case`; `cargo xtask layout` checks it)\n";
pub(crate) const END: &str = "// cases: end\n";

pub(crate) fn check(root: &Path) -> Findings {
    let mut findings = Vec::new();
    for (src, tests) in TREES {
        mirror(root, src, tests, &mut findings);
        declarations(root, src, &mut findings);
        declarations(root, tests, &mut findings);
        inline_tests(root, src, &mut findings);
    }
    facades(root, &mut findings);
    constructors(root, &mut findings);
    allow_attributes(root, &mut findings);
    for dir in ["src", "tests", "benchmarks", "xtask"] {
        for link in walk::links(root, dir) {
            findings.push(format!(
                "layout: {link} is a symlink; code and cases must be real files"
            ));
        }
    }
    cases(root, &mut findings);
    findings
}

fn rust_files(root: &Path, dir: &str) -> BTreeSet<String> {
    walk::files(root, dir)
        .into_iter()
        .filter(|f| f.ends_with(".rs"))
        .filter(|f| !(f == RUNNER || f.starts_with("tests/benchmarks/")))
        .map(|f| f[dir.len() + 1..].to_owned())
        .collect()
}

fn mirror(root: &Path, src: &str, tests: &str, findings: &mut Findings) {
    let sources = rust_files(root, src);
    let mirrors = rust_files(root, tests);
    for rel in sources.difference(&mirrors) {
        findings.push(format!("layout: {src}/{rel} has no mirror {tests}/{rel}"));
    }
    for rel in mirrors.difference(&sources) {
        findings.push(format!(
            "layout: orphan test {tests}/{rel} (no {src}/{rel})"
        ));
    }
}

fn declarations(root: &Path, dir: &str, findings: &mut Findings) {
    for rel in rust_files(root, dir) {
        if rel == "lib.rs" || (rel == "main.rs" && dir.ends_with("src")) {
            continue;
        }
        let (parent, name) = match rel.rsplit_once('/') {
            Some((parent, file)) => (
                format!("{parent}.rs"),
                file.trim_end_matches(".rs").to_owned(),
            ),
            None => ("lib.rs".to_owned(), rel.trim_end_matches(".rs").to_owned()),
        };
        let text = walk::read(root, &format!("{dir}/{parent}"));
        match modules(&text).into_iter().find(|(module, _)| *module == name) {
            None => findings.push(format!(
                "layout: {dir}/{rel} is not declared; add `mod {name};` to {dir}/{parent}"
            )),
            Some((_, true)) => findings.push(format!(
                "layout: {dir}/{parent} declares `mod {name}` under a cfg, which can compile {dir}/{rel} out"
            )),
            Some((_, false)) => {}
        }
    }
}

fn modules(text: &str) -> Vec<(String, bool)> {
    let trees = syntax::parse(text).unwrap_or_default();
    let mut out = Vec::new();
    let mut cfg = false;
    for k in 0..trees.len() {
        match &trees[k..] {
            [
                Tree::Punct('#', _),
                Tree::Group(Delimiter::Bracket, body, _),
                ..,
            ] => {
                cfg |= body
                    .first()
                    .is_some_and(|t| t.is_ident("cfg") || t.is_ident("cfg_attr"));
            }
            [m, Tree::Ident(name, _), Tree::Punct(';', _), ..] if m.is_ident("mod") => {
                out.push((name.clone(), cfg));
                cfg = false;
            }
            [Tree::Punct(';', _) | Tree::Group(Delimiter::Brace, ..), ..] => cfg = false,
            _ => {}
        }
    }
    out
}

fn allow_attributes(root: &Path, findings: &mut Findings) {
    for dir in ["src", "tests", "xtask"] {
        for file in walk::files(root, dir)
            .into_iter()
            .filter(|f| f.ends_with(".rs"))
        {
            for (n, line) in walk::read(root, &file).lines().enumerate() {
                let l = line.trim_start();
                if l.starts_with("#[allow(") || l.starts_with("#![allow(") {
                    findings.push(format!(
                        "layout: {file}:{} uses allow; write #[expect(…, reason = \"…\")]",
                        n + 1
                    ));
                }
            }
        }
    }
}

fn inline_tests(root: &Path, src: &str, findings: &mut Findings) {
    for rel in rust_files(root, src) {
        let file = format!("{src}/{rel}");
        let trees = match syntax::parse(&walk::read(root, &file)) {
            Ok(trees) => trees,
            Err(e) => {
                findings.push(format!("layout: {file} {e}"));
                continue;
            }
        };
        let test = syntax::attributes(&trees)
            .into_iter()
            .find(|(body, _)| syntax::idents(body).iter().any(|(name, _)| *name == "test"));
        if let Some((_, line)) = test {
            findings.push(format!(
                "layout: {file}:{line} holds an inline test; move it to its mirror"
            ));
        }
    }
}

fn constructors(root: &Path, findings: &mut Findings) {
    for rel in rust_files(root, "src") {
        let trees = syntax::parse(&walk::read(root, &format!("src/{rel}"))).unwrap_or_default();
        for (_, _, line) in syntax::pairs(&trees)
            .into_iter()
            .filter(|pair| (pair.0, pair.1) == ("fn", "new"))
        {
            findings.push(format!(
                "layout: src/{rel}:{line} defines `fn new`, which cargo-mutants never mutates; implement TryFrom or name the constructor"
            ));
        }
    }
}

fn facades(root: &Path, findings: &mut Findings) {
    for file in walk::files(root, "src") {
        if file.matches('/').count() != 1 || !file.ends_with(".rs") || file == "src/main.rs" {
            continue;
        }
        let trees = match syntax::parse(&walk::read(root, &file)) {
            Ok(trees) => trees,
            Err(e) => {
                findings.push(format!("layout: {file} {e}"));
                continue;
            }
        };
        for item in syntax::items(&trees) {
            if !declares(item) {
                let line = item.first().map_or(0, Tree::line);
                findings.push(format!(
                    "layout: {file}:{line} holds code; a layer root only declares modules and re-exports"
                ));
            }
        }
    }
}

fn declares(item: &[Tree]) -> bool {
    let mut rest = item;
    let public = rest.first().is_some_and(|t| t.is_ident("pub"));
    if public {
        rest = &rest[1..];
        if let Some(Tree::Group(Delimiter::Parenthesis, scope, _)) = rest.first() {
            if !matches!(scope.as_slice(), [only] if only.is_ident("crate")) {
                return false;
            }
            rest = &rest[1..];
        }
    }
    match rest {
        [word, Tree::Ident(_, _), end] => word.is_ident("mod") && end.is_punct(';'),
        [word, .., end] if public && word.is_ident("use") => end.is_punct(';'),
        _ => false,
    }
}

fn table(ids: &[String]) -> String {
    let mut out = String::from(BEGIN);
    let mut names: Vec<&String> = ids.iter().collect();
    names.sort();
    for id in names {
        out.push_str(&format!(
            "#[path = \"benchmarks/{id}/case.rs\"]\nmod n{id};\n"
        ));
    }
    out.push_str("\nconst CASES: &[(&str, Measure)] = &[\n");
    for id in ids {
        out.push_str(&format!("    (\"{id}\", n{id}::measure),\n"));
    }
    out.push_str("];\n");
    out.push_str(END);
    out
}

pub(crate) fn current_table(runner: &str) -> Result<(usize, usize), String> {
    let start = runner
        .find(BEGIN)
        .ok_or_else(|| format!("{RUNNER} lacks the line `{}`", BEGIN.trim_end()))?;
    let end = runner[start..]
        .find(END)
        .map(|i| start + i + END.len())
        .ok_or_else(|| format!("{RUNNER} lacks the line `{}`", END.trim_end()))?;
    Ok((start, end))
}

fn cases(root: &Path, findings: &mut Findings) {
    let ids = match case::ids(root) {
        Ok(ids) => ids,
        Err(e) => {
            findings.push(format!("layout: {e}"));
            return;
        }
    };
    for id in &ids {
        if let Err(e) = case::Case::load(root, id) {
            findings.push(format!("layout: {e}"));
        }
        if !root
            .join(format!("tests/benchmarks/{id}/case.rs"))
            .is_file()
        {
            findings.push(format!("layout: missing tests/benchmarks/{id}/case.rs"));
        }
    }
    let runner = walk::read(root, RUNNER);
    if !ids.is_empty() || !runner.is_empty() {
        match current_table(&runner) {
            Ok((start, end)) if runner[start..end] == table(&ids) => {}
            Ok(_) => findings.push(format!(
                "layout: the case table in {RUNNER} differs from benchmarks/; run `cargo xtask new-case` or restore it"
            )),
            Err(e) => findings.push(format!("layout: {e}")),
        }
    }
    let known: BTreeSet<&str> = ids.iter().map(String::as_str).collect();
    for test in walk::files(root, "tests/benchmarks") {
        if let Some(id) = test.split('/').nth(2)
            && !known.contains(id)
        {
            findings.push(format!("layout: orphan {test} (no benchmarks/{id}/)"));
        }
    }
}

pub(crate) fn new_case(root: &Path, slug: &str, reference: &str) -> Findings {
    let slug_ok = !slug.is_empty()
        && slug
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_');
    if !slug_ok || !Reference::NAMES.contains(&reference) {
        return vec![format!(
            "usage: cargo xtask new-case <slug: [a-z0-9_]+> <reference: {}>",
            Reference::NAMES.join("|")
        )];
    }
    let mut ids = match case::ids(root) {
        Ok(ids) => ids,
        Err(e) => return vec![format!("new-case: {e}")],
    };
    let locked = crate::lock::blocks(root);
    let next = ids
        .iter()
        .map(String::as_str)
        .chain(locked.iter().map(String::as_str))
        .filter_map(|id| case::parse_id(id).ok())
        .max()
        .unwrap_or(0)
        + 1;
    let id = format!("{next}_{slug}");
    let runner = walk::read(root, RUNNER);
    let (start, end) = match current_table(&runner) {
        Ok(span) => span,
        Err(e) => return vec![format!("new-case: {e}")],
    };
    ids.push(id.clone());
    let (tier, claims) = if reference == "vasp-measured" {
        ("claim", "\"accuracy\", \"speed\"")
    } else {
        ("push", "\"correctness\"")
    };
    let case = format!(
        "[case]\ntier = \"{tier}\"\nstatus = \"planned\"\nclaims = [{claims}]\nreference = \"{reference}\"\n\n[tolerance]\n"
    );
    if let Err(e) = case::Case::parse(&case) {
        return vec![format!("new-case: the scaffold for {id} is invalid: {e}")];
    }
    let measure = "use xtask::harness::{Evidence, Metrics};\n\npub fn measure(_evidence: &Evidence) -> Result<Metrics, String> {\n    Err(\"planned: measure the engine output here\".into())\n}\n";
    let mut what = walk::read(root, results::WHAT);
    if !what.is_empty() && !what.ends_with('\n') {
        what.push('\n');
    }
    what.push_str(&format!(
        "\n[{next}]\nwhat = \"{}\"\nmetric = []\nunit = \"\"\n",
        slug.replace('_', " ")
    ));
    let writes = [
        (format!("benchmarks/{id}/case.toml"), case),
        (results::WHAT.to_owned(), what),
        (format!("tests/benchmarks/{id}/case.rs"), measure.to_owned()),
        (
            RUNNER.to_owned(),
            format!("{}{}{}", &runner[..start], table(&ids), &runner[end..]),
        ),
    ];
    for (path, body) in writes {
        let path = root.join(path);
        if let Err(e) = path
            .parent()
            .map_or(Ok(()), fs::create_dir_all)
            .and_then(|()| fs::write(&path, body))
        {
            return vec![format!("new-case: {}: {e}", path.display())];
        }
    }
    println!(
        "created {id}: write input.toml, [tolerance], measure(), and its phrase in {}; then run cargo xtask lock --reviewer <name> --reason <text>",
        results::WHAT
    );
    Vec::new()
}
